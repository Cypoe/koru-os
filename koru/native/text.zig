var fg: u32 = 0x00FFFFFF;
var bg: u32 = 0x00000000;
var cx: u32 = 0;
var cy: u32 = 0;
var W: u32 = 0;
var H: u32 = 0;

pub fn dims() struct { w: u32, h: u32 } {
    return .{ .w = W, .h = H };
}
pub fn syncDims() void {
    var info: fb.Info = undefined;
    if (fb.koruos_fb_info(&info) == 0) return;
    W = info.width; H = info.height;
    cx = 0; cy = 0;
}
pub fn init() void {
    var info: fb.Info = undefined;
    if (fb.koruos_fb_info(&info) == 0) return;
    W = info.width; H = info.height;
    _ = fb.koruos_fb_fill(0, 0, W, H, bg);
    cx = 8; cy = 8;
}
pub fn clear() void {
    if (W != 0) _ = fb.koruos_fb_fill(0, 0, W, H, bg);
    cx = 8; cy = 8;
}
fn glyphAt(x: u32, y: u32, g: u8) void {
    const f = font[g & 0x7F];
    var r: usize = 0;
    while (r < 8) : (r += 1) {
        const bits = f[r];
        var c: usize = 0;
        while (c < 8) : (c += 1) {
            if (((bits >> @intCast(c)) & 1) != 0) {
                _ = fb.koruos_fb_px(x + @as(u32, @intCast(c)), y + @as(u32, @intCast(r)), fg);
            }
        }
    }
}
// console->udp mirror: every rendered line also streams to the listener —
// the wire log IS the screen log. Hook set by boot.zig (net.mirror) —
// text.zig stays dependency-free, no module edge back into net.
pub var udpMirror: ?*const fn ([]const u8) void = null;
var mir: [224]u8 = undefined;
var mir_len: usize = 0;
fn mirrorFlush() void {
    if (mir_len == 0) return;
    if (udpMirror) |f| f(mir[0..mir_len]);
    mir_len = 0;
}
pub fn putc(ch: u8) void {
    if (W == 0) return;
    if (ch == '\n' or ch == '\r') { newline(); return; }
    if (ch == 0x08) { if (cx >= CW + 8) cx -= CW; if (mir_len > 0) mir_len -= 1; return; }
    if (mir_len < mir.len) mir[mir_len] = ch;
    if (mir_len < mir.len) mir_len += 1;
    if (cx + CW >= W) newline();
    glyphAt(cx, cy, ch);
    cx += CW;
}
pub fn puts(s: [*:0]const u8) void {
    var i: usize = 0;
    while (s[i] != 0) : (i += 1) putc(s[i]);
}
pub fn puthex(b: u8) void {
    const digs = "0123456789ABCDEF";
    putc(digs[b >> 4]);
    putc(digs[b & 0xF]);
}
pub fn putdec(v: u64) void {
    if (v >= 10) putdec(v / 10);
    putc('0' + @as(u8, @intCast(v % 10)));
}
pub fn newline() void {
    mirrorFlush();
    cx = 8; cy += CH;
    if (cy + CH >= H) cy = H - CH - 8;
}
pub fn setColor(f: u32, b: u32) void { fg = f; bg = b; }
